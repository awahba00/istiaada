    errors = []
    for i, (fkey, old, new) in enumerate(EDITS):
        s = contents[fkey]
        n = s.count(old)
        if n != 1:
            errors.append(f"[{i}] file={fkey} count={n} :: {old[:70]}...")
            continue
        contents[fkey] = s.replace(old, new)
        applied += 1
    if errors:
        print(f"FAILED — applied {applied}/{len(EDITS)}")
        for e in errors:
            print(e)
        sys.exit(1)
    for k, v in FILES.items():
        io.open(v, "w", encoding="utf-8").write(contents[k])
    print(f"OK — {applied} replacements written across 3 knowledge files")

