FILES = {
    "knowledge-core.ts": CORE,
    "knowledge-wellbeing.ts": WELLBEING,
    "knowledge-recovery.ts": RECOVERY,
    "knowledge-new.ts": NEW,
}

total_applied = 0
total_failed = 0
for fname, edits in FILES.items():
    path = BASE + fname
    with open(path, encoding="utf-8") as f:
        content = f.read()
    print(f"\n=== {fname}: {len(edits)} edits ===")
    for old, new, card_id, ptype, reason in edits:
        n = content.count(old)
        if n == 1:
            content = content.replace(old, new)
            total_applied += 1
            print(f"  OK  [{card_id}] ({ptype})")
        elif n == 0:
            # maybe already applied?
            already = content.count(new)
            if already >= 1:
                print(f"  SKIP [{card_id}] — already applied")
            else:
                total_failed += 1
                print(f"  FAIL [{card_id}] — old string NOT FOUND: {old[:60]}...")
        else:
            total_failed += 1
            print(f"  FAIL [{card_id}] — old string appears {n} times (ambiguous): {old[:60]}...")
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)

print(f"\n=== SUMMARY: applied={total_applied}, failed={total_failed} ===")
sys.exit(1 if total_failed else 0)
